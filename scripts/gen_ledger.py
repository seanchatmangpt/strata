#!/usr/bin/env python3
"""Receipt -> ledger projection (E57b, ERRC2 C1/C2).

Given a directory of validated lane-receipt JSONs (docs/receipts/ convention),
generate the markdown ledger table deterministically: same input directory =>
byte-identical output (the anti-drift property). Every receipt is validated
first (receipt_validate.structural_errors, always-on; jsonschema when the
module is present); invalid input is REFUSED with a typed error and no output
is written.

Usage:
  python3 scripts/gen_ledger.py <receipts_dir> [out.md]
  python3 scripts/gen_ledger.py <receipts_dir> out.md --check   # exit 0 iff out.md already identical
  python3 scripts/gen_ledger.py --selftest

SCOPE NOTE (deliberate, 2026-10-13): this generator emits the STATUS TABLE
only. docs/innovation/ERRC2_mutation_ledger.md's Verdict Table, Survivors,
Findings, Gate Output, and Totals sections are hand-maintained evidence
prose and are NOT generated or clobbered by this script. Re-run
`python3 scripts/gen_ledger.py docs/receipts docs/innovation/ledger_status_table.md`
to refresh the generated table; the ledger prose stays manual.

Non-receipt JSON files (e.g. cleanup-plan.json, which lacks a `lane` field)
are SKIPPED with a disclosed note, not refused — they are out of the lane-
receipt domain, not invalid receipts. Files that HAVE a `lane` field but
fail validation are still REFUSED with a typed error.

Determinism: rows sorted by (lane, started_at, source filename); no
timestamps, paths, or environment values enter the output.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from receipt_validate import structural_errors, DEFAULT_SCHEMA, HAVE_JSONSCHEMA  # noqa: E402

TEST_COUNT_RE = re.compile(r"(\d+)\s*/\s*(\d+)")


def load_receipts(receipts_dir):
    """Load + validate every *.json in dir. Returns (receipts, skipped).
    Receipts are (filename, dict); skipped is a list of disclosed
    non-receipt filenames (JSON without a `lane` field = not in the
    lane-receipt domain, e.g. cleanup-plan.json); corrupt is a list of
    (filename, error) for files corrupt beyond JSON parsing — reported
    and skipped, never rewritten. Raises TypedRefusal on any
    parseable-but-invalid lane receipt."""
    files = sorted(p for p in Path(receipts_dir).glob("*.json"))
    if not files:
        raise TypedRefusal("EMPTY_INPUT", f"no *.json receipts in {receipts_dir}")
    out = []
    skipped = []
    corrupt = []
    for p in files:
        try:
            r = json.loads(p.read_text())
        except json.JSONDecodeError as exc:
            # Corrupt beyond parsing: reported and skipped (task constraint —
            # receipt content is evidence and is never rewritten).
            corrupt.append((p.name, str(exc)))
            continue
        except OSError as exc:
            raise TypedRefusal("UNREADABLE", f"{p.name}: {exc}")
        if not isinstance(r, dict) or "lane" not in r:
            skipped.append(p.name)
            continue
        engine = "jsonschema" if HAVE_JSONSCHEMA else "structural-fallback"
        errs = structural_errors(r, json.loads(DEFAULT_SCHEMA.read_text()))
        if errs:
            raise TypedRefusal(
                "INVALID_RECEIPT",
                f"{p.name} refused by receipt_validate ({engine}):\n    "
                + "\n    ".join(errs))
        out.append((p.name, r))
    return out, skipped, corrupt


class TypedRefusal(Exception):
    def __init__(self, kind, detail):
        super().__init__(f"{kind}: {detail}")
        self.kind = kind
        self.detail = detail


def extract_tests(verification):
    """(passed, failed) ints; absent counts -> None (rendered as '-')."""
    passed = verification.get("tests_passed")
    failed = verification.get("tests_failed")
    if passed is None and failed is None:
        m = TEST_COUNT_RE.search(verification.get("command", ""))
        if m:
            passed, failed = int(m.group(1)), int(m.group(2))
    return passed, failed


def render_deviation(d):
    # Legacy string deviations (v1 receipts) are treated as SCOPE_NOTE by
    # the validator's dev_notes(); rendered with their historical form kept.
    if isinstance(d, str):
        return f"SCOPE_NOTE(legacy): {d}"
    return f"{d.get('kind', '?')}: {d.get('note', '')}"


def esc(text):
    """Escape pipe/brace/newline so one receipt can't break the table."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render_table(receipts):
    """receipts: list of (filename, dict), pre-sorted. Returns markdown."""
    lines = [
        "# Lane Ledger (generated)",
        "",
        "Source of truth: `docs/receipts/*.json` validated against",
        "`docs/schemas/LANE_RECEIPT.schema.json`. Generated by",
        "`scripts/gen_ledger.py` — do not hand-edit; re-run instead.",
        "",
        "| Lane | Wave | Status | Verify (pass/fail) | Deviations |",
        "|---|---|---|---|---|",
    ]
    for fname, r in receipts:
        passed, failed = extract_tests(r.get("verification", {}))
        v = f"{passed}/{failed}" if passed is not None or failed is not None else "-"
        devs = r.get("deviations", [])
        dev = "; ".join(esc(render_deviation(d)) for d in devs) if devs else "-"
        fix = r.get("fix_owner")
        if fix:
            dev = (dev + f" fix_owner={fix}") if dev != "-" else f"fix_owner={fix}"
        lines.append(
            f"| {r['lane']} | {r['wave']} | {r['status']} | {v} | {dev} |")
    lines.append("")
    lines.append(f"{len(receipts)} receipts.")
    return "\n".join(lines) + "\n"


def run_selftest():
    """Mutate a copy of a valid receipt in a temp dir; show refusal + verify
    the happy path is deterministic (two runs byte-equal)."""
    receipts_dir = REPO / "docs/receipts"
    ok = True

    # 1. happy path + determinism
    with tempfile.TemporaryDirectory() as td:
        outs = []
        for i in (1, 2):
            op = Path(td) / f"ledger_{i}.md"
            rc = main([str(receipts_dir), str(op)])
            if rc != 0:
                print(f"SELFTEST FAIL: generation run {i} exited {rc}")
                return 1
            outs.append(op.read_bytes())
        if outs[0] != outs[1]:
            print("SELFTEST FAIL: two runs not byte-identical (anti-drift violated)")
            ok = False
        else:
            print(f"SELFTEST PASS: determinism — two runs byte-identical ({len(outs[0])} bytes)")

    # 2. mutation battery: each mutation must be refused
    mutations = [
        ("status PENDING (pre-receipt state)", lambda r: r.__setitem__("status", "PENDING")),
        ("missing verification", lambda r: r.pop("verification")),
        ("bad output_digest", lambda r: r["verification"].__setitem__("output_digest", "sha256:deadbeef")),
        ("empty owned_files", lambda r: r.__setitem__("owned_files", [])),
        ("bad lane id", lambda r: r.__setitem__("lane", "l150")),
        ("finished before started", lambda r: r.__setitem__("finished_at", "2020-01-01T00:00:00Z")),
    ]
    base = json.loads((receipts_dir / "L150.json").read_text())
    for label, mutate in mutations:
        r = json.loads(json.dumps(base))
        mutate(r)
        with tempfile.TemporaryDirectory() as td:
            p = Path(td) / "mutated.json"
            p.write_text(json.dumps(r))
            try:
                load_receipts(td)
                print(f"SELFTEST FAIL: mutation NOT refused — {label}")
                ok = False
            except TypedRefusal as exc:
                print(f"SELFTEST PASS: refused [{exc.kind}] — {label}")
    return 0 if ok else 1


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--selftest" in argv:
        return run_selftest()
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    receipts_dir = argv[0]
    rest = [a for a in argv[1:] if a != "--check"]
    check = "--check" in argv
    out_path = rest[0] if rest else None
    if check and not out_path:
        print("REFUSED [USAGE] --check requires an output path")
        return 2
    try:
        receipts, skipped, corrupt = load_receipts(receipts_dir)
    except TypedRefusal as exc:
        print(f"REFUSED [{exc.kind}] {exc.detail}")
        return 1
    for name in skipped:
        print(f"SKIPPED (not a lane receipt — no `lane` field): {name}")
    for name, err in corrupt:
        print(f"SKIPPED (CORRUPT — unparseable JSON, reported not rewritten): {name}: {err}")
    receipts.sort(key=lambda fr: (fr[1]["lane"], fr[1]["started_at"], fr[0]))
    md = render_table(receipts)
    if out_path:
        p = Path(out_path)
        if check:
            existing = p.read_text() if p.exists() else None
            if existing == md:
                print(f"CHECK OK: {out_path} identical to regenerated output ({len(receipts)} receipts)")
                return 0
            print(f"CHECK FAIL: {out_path} differs from regenerated output")
            return 1
        p.write_text(md)
        print(f"WROTE {out_path} ({len(receipts)} receipts, {len(md)} bytes)")
    else:
        sys.stdout.write(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())

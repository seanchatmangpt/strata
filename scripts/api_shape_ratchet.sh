#!/usr/bin/env bash
# api_shape_ratchet.sh — executable API-shape ratchet over strata_protocol/src/consensus/*
# ERRC tollgate meta C2 (docs/innovation/ERRC_tollgate_meta.md). Converts the MEV
# court's hand-pinned no-priority surface enumeration into an executable gate.
#
# Modes:
#   first run (manifest absent or empty) -> GENERATES scripts/consensus_surface.txt, exit 0
#   otherwise                            -> regenerates inventory, refuses drift with typed diff
#
# Inventory entry: "<file>::<name> <kind> <pub fn|pub const fn|pub const|pub struct ...>"
# Manifest: comment lines, "hash:" line, then sorted inventory entries.
#
# bash 3.2-safe. Exit codes: 0 = match/generate, 1 = drift, 2 = env error.
set -u

REPO="$(cd "$(dirname "$0")/.." && pwd)"
SRC_DIR="$REPO/strata_protocol/src/consensus"
MANIFEST="$REPO/scripts/consensus_surface.txt"

[ -d "$SRC_DIR" ] || { echo "ENV_ERROR: no consensus dir at $SRC_DIR" >&2; exit 2; }
command -v shasum >/dev/null 2>&1 || { echo "ENV_ERROR: shasum not found" >&2; exit 2; }

# collapse whitespace runs to single spaces, trim ends
normalize_signature() {
  printf '%s' "$1" | tr -s ' \t' ' ' | sed -e 's/^ //' -e 's/ $//'
}

# generate_inventory -> sorted "<file>::<name> <kind> <signature>" lines on stdout
generate_inventory() {
  # shellcheck disable=SC2044
  for f in $(find "$SRC_DIR" -name '*.rs' | sort); do
    base="$(basename "$f")"
    grep -nE '^[[:space:]]*pub (fn|const|struct)[[:space:]]' "$f" | while IFS= read -r line; do
      body="${line#*:}"   # strip "NN:" prefix (line numbers not part of identity)
      sig="$(normalize_signature "$body")"
      case "$sig" in
        "pub struct "*)   kind="struct" ;;
        "pub const fn "*) kind="const_fn" ;;
        "pub const "*)    kind="const" ;;
        "pub fn "*)       kind="fn" ;;
        *)                kind="other" ;;
      esac
      # name: identifier after "pub [const] [fn]" — covers all four item shapes
      name="$(printf '%s' "$sig" | sed -E 's/^pub (const )?(fn |struct )?([A-Za-z_][A-Za-z0-9_]*).*/\3/')"
      printf '%s::%s %s %s\n' "$base" "$name" "$kind" "$sig"
    done
  done | sort
}

inventory="$(generate_inventory)"
if [ -z "$inventory" ]; then
  echo "ENV_ERROR: empty inventory from $SRC_DIR" >&2
  exit 2
fi

hash="$(printf '%s\n' "$inventory" | shasum -a 256 | cut -d' ' -f1)"

if [ ! -s "$MANIFEST" ]; then
  {
    echo "# consensus API surface manifest — GENERATED by scripts/api_shape_ratchet.sh"
    echo "# ERRC tollgate meta C2 (docs/innovation/ERRC_tollgate_meta.md)."
    echo "# Regenerate: bash scripts/api_shape_ratchet.sh (after reviewing the typed diff)."
    echo "# Refuses: added pub fn/const/struct, removed entries, changed signature class."
    echo "hash: $hash"
    printf '%s\n' "$inventory"
  } > "$MANIFEST"
  echo "GENERATE: manifest created at scripts/consensus_surface.txt (hash $hash)"
  count="$(printf '%s\n' "$inventory" | wc -l | tr -d ' ')"
  files="$(find "$SRC_DIR" -name '*.rs' | wc -l | tr -d ' ')"
  echo "GENERATE: $count pub items pinned across $files files"
  exit 0
fi

# ---- check mode ----
pinned_hash="$(sed -n 's/^hash: //p' "$MANIFEST" | head -1)"
pinned_entries="$(grep -vE '^(#|hash:)' "$MANIFEST" | sed '/^[[:space:]]*$/d')"

if [ "$hash" = "$pinned_hash" ]; then
  echo "OK: consensus API surface matches manifest ($hash)"
  exit 0
fi

# ---- typed diff ----
drift_report="$(mktemp)"
current_names="$(printf '%s\n' "$inventory" | awk '{print $1}')"
pinned_names="$(printf '%s\n' "$pinned_entries" | awk '{print $1}')"

# ADDED: in current, not pinned
added="$(comm -13 <(printf '%s\n' "$pinned_names" | sort) <(printf '%s\n' "$current_names" | sort))"
if [ -n "$added" ]; then
  {
    echo "ADDED (new pub surface not in manifest):"
    printf '%s\n' "$added" | while IFS= read -r k; do
      printf '%s\n' "$inventory" | grep -F -- "$k"
    done
    echo
  } >> "$drift_report"
fi

# REMOVED: pinned, not in current
removed="$(comm -23 <(printf '%s\n' "$pinned_names" | sort) <(printf '%s\n' "$current_names" | sort))"
if [ -n "$removed" ]; then
  {
    echo "REMOVED (pinned pub surface vanished):"
    printf '%s\n' "$removed"
    echo
  } >> "$drift_report"
fi

# CHANGED: same file::name key, different kind+signature remainder
changed="$(awk '
  NR==FNR { if ($0 !~ /^#/) pinned[$1] = substr($0, length($1) + 2); next }
  { cur[$1] = substr($0, length($1) + 2) }
  END {
    for (k in cur) if ((k in pinned) && pinned[k] != cur[k])
      print k " pinned[" pinned[k] "] vs current[" cur[k] "]"
  }' <(printf '%s\n' "$pinned_entries") <(printf '%s\n' "$inventory") | sort)"
if [ -n "$changed" ]; then
  {
    echo "CHANGED (same name, different signature class):"
    printf '%s\n' "$changed" | sed 's/^/  /'
    echo
  } >> "$drift_report"
fi

echo "API_SHAPE_DRIFT: inventory hash mismatch"
echo "  pinned:  $pinned_hash"
echo "  current: $hash"
cat "$drift_report"
rm -f "$drift_report"
echo "REFUSED: consensus API surface changed. Update fn-pointer courts in"
echo "  strata_protocol/tests/mev_falsify_court.rs (or re-pin with intent:"
echo "  bash scripts/api_shape_ratchet.sh after reviewing the typed diff above)."
exit 1
